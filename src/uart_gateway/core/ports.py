"""目前切片需要的阻塞裝置介面。"""

from typing import Protocol

from .models import AdapterInfo


class SerialPort(Protocol):
    def open(self) -> None: ...
    def read(self, size: int) -> bytes: ...
    def write(self, data: bytes) -> int: ...
    def close(self) -> None: ...
    def describe(self) -> AdapterInfo: ...
